/// Pure-Rust, zero-Node SVG optimizer.
/// Strips XML prologs, comments, `<metadata>` blocks, and redundant inter-tag whitespace.
pub fn optimize_svg(input: &str) -> String {
    let mut s = input.to_owned();

    // 1. Strip XML declaration `<?xml ... ?>`
    while let Some(start) = s.find("<?xml") {
        if let Some(end_rel) = s[start..].find("?>") {
            s.replace_range(start..start + end_rel + 2, "");
        } else {
            break;
        }
    }

    // 2. Strip XML comments `<!-- ... -->`
    while let Some(start) = s.find("<!--") {
        if let Some(end_rel) = s[start..].find("-->") {
            s.replace_range(start..start + end_rel + 3, "");
        } else {
            break;
        }
    }

    // 3. Strip `<metadata>...</metadata>` blocks
    while let Some(start) = s.find("<metadata") {
        if let Some(end_rel) = s[start..].find("</metadata>") {
            s.replace_range(start..start + end_rel + "</metadata>".len(), "");
        } else {
            break;
        }
    }

    // 4. Collapse newlines & inter-tag whitespace cleanly without touching quoted attribute values.
    let mut out = String::with_capacity(s.len());
    let mut in_quotes = false;
    let mut quote_char = '"';
    let mut prev_space = false;

    for ch in s.trim().chars() {
        if in_quotes {
            out.push(ch);
            if ch == quote_char {
                in_quotes = false;
            }
            continue;
        }

        if ch == '"' || ch == '\'' {
            in_quotes = true;
            quote_char = ch;
            prev_space = false;
            out.push(ch);
            continue;
        }

        if ch.is_whitespace() {
            if !prev_space && !out.ends_with('>') {
                out.push(' ');
                prev_space = true;
            }
            continue;
        }

        if ch == '<' && out.ends_with(' ') {
            out.pop();
        }
        prev_space = false;
        out.push(ch);
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn optimizes_svg_by_stripping_prolog_comments_metadata_and_whitespace() {
        let raw = r##"<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by editor -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <metadata><rdf>editor info</rdf></metadata>
  <rect   width="64"   height="64"   fill="#111827" />
</svg>
"##;
        let opt = optimize_svg(raw);
        assert!(!opt.contains("<?xml"));
        assert!(!opt.contains("<!--"));
        assert!(!opt.contains("<metadata>"));
        assert!(opt.contains("fill=\"#111827\""));
        assert!(opt.len() < raw.len());
    }
}
